#!/usr/bin/env python3
"""Embed the authoritative .strings tables in the tweak without a runtime bundle."""

import argparse
import json
from pathlib import Path
import plistlib
import re


def parse_strings(text, source):
    # This project's .strings use quoted JSON-compatible strings and C-style comments.
    # Reject other OpenStep syntax rather than silently dropping or changing translations.
    ignored = re.compile(r"\s+|/\*.*?\*/|//[^\n]*(?:\n|$)", re.DOTALL)
    decoder = json.JSONDecoder()
    position = 0

    def fail(message, offset):
        line = text.count("\n", 0, offset) + 1
        column = offset - text.rfind("\n", 0, offset)
        raise ValueError(f"{source}:{line}:{column}: {message}")

    def skip():
        nonlocal position
        while match := ignored.match(text, position):
            position = match.end()

    def quoted_string():
        nonlocal position
        skip()
        if position == len(text) or text[position] != '"':
            fail("expected a quoted string", position)
        try:
            value, position = decoder.raw_decode(text, position)
        except json.JSONDecodeError as error:
            fail(error.msg, error.pos)
        return value

    def consume(symbol):
        nonlocal position
        skip()
        if position == len(text) or text[position] != symbol:
            fail(f"expected '{symbol}'", position)
        position += 1

    table = {}
    skip()
    while position < len(text):
        start = position
        key = quoted_string()
        consume("=")
        value = quoted_string()
        consume(";")
        if key in table:
            fail(f"duplicate key {key!r}", start)
        table[key] = value
        skip()
    return table


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    info = plistlib.loads((args.source / "Info.plist").read_bytes())
    codes = info["CFBundleLocalizations"]
    development_region = info["CFBundleDevelopmentRegion"]
    if codes != ["en", "zh-Hant", "zh-Hans", "ja", "ko"] or development_region != "en":
        parser.error("Update the language preference mapping before changing supported languages")
    tables = {}
    for code in codes:
        path = args.source / f"{code}.lproj" / "Localizable.strings"
        try:
            tables[code] = parse_strings(path.read_text(encoding="utf-8"), path)
        except (OSError, ValueError) as error:
            parser.error(str(error))

    payload = plistlib.dumps({
        "developmentRegion": development_region,
        "localizations": codes,
        "tables": tables,
    }, fmt=plistlib.FMT_BINARY, sort_keys=True)
    lines = [
        "// Generated by scripts/generate-localization.py. Edit resources/localization instead.",
        "#pragma once",
        "static const unsigned char TPLocalizationData[] = {",
    ]
    lines.extend(
        "    " + ", ".join(f"0x{byte:02x}" for byte in payload[offset:offset + 16]) + ","
        for offset in range(0, len(payload), 16)
    )
    output = "\n".join(lines + ["};", ""]).encode("utf-8")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_bytes() != output:
        args.output.write_bytes(output)


if __name__ == "__main__":
    main()
